import { cp, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import { load } from 'cheerio';
import { SITE_URL, SOURCE_URL, legacyRoutes } from './site-config.mjs';

const source = resolve('site');
const output = resolve('out');
async function filesBelow(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  return (await Promise.all(entries.map(entry => entry.isDirectory()
    ? filesBelow(join(directory, entry.name)) : [join(directory, entry.name)]))).flat();
}
const escape = text => String(text).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
const scriptJson = data => JSON.stringify(data).replaceAll('<', '\\u003c');
const pathnameFor = file => '/' + relative(source, file).replaceAll('\\', '/').replace(/index\.html$/, '');
const referenceFiles = await filesBelow(source);
const publicPages = [];
const referenceHome = load(await readFile(join(source, 'index.html'), 'utf8'));

for (const file of referenceFiles) {
  if (file.endsWith('source-version.json')) continue;
  const destination = join(output, relative(source, file));
  await mkdir(resolve(destination, '..'), { recursive: true });
  if (!file.endsWith('.html')) {
    await cp(file, destination);
    continue;
  }
  const pathname = pathnameFor(file);
  const isPublic = !pathname.startsWith('/pruebas/');
  // Preserve the original markup, styles and interaction scripts. Only links and
  // nonvisual production metadata differ from the supplied v53 snapshot.
  let html = await readFile(file, 'utf8');
  html = html.replace(/((?:href|src|data-src|data-preview|data-url|data-project-url)=")https:\/\/(?:www\.)?oriavision\.com\.ar(?=\/)/g, '$1');
  html = html.replaceAll(SOURCE_URL, SITE_URL);
  html = html.replace(/<meta\b[^>]*name="robots"[^>]*>/gi, '');
  html = html.replace(/<link\b[^>]*rel="canonical"[^>]*>/gi, '');
  const $ = load(html);
  const title = $('title').text();
  const description = $('meta[name="description"]').attr('content') || title;
  const canonical = SITE_URL + pathname;
  const image = new URL($('main img[src]').first().attr('src') || '/images/oriavision-logo-original.jpg', SITE_URL).href;
  const schema = {
    '@context': 'https://schema.org',
    '@graph': [
      { '@type': 'Organization', '@id': SITE_URL + '/#organization', name: 'Oriavision', url: SITE_URL + '/', logo: SITE_URL + '/images/oriavision-logo-original.jpg' },
      { '@type': 'WebSite', '@id': SITE_URL + '/#website', name: 'Oriavision', url: SITE_URL + '/', inLanguage: 'es-AR', publisher: { '@id': SITE_URL + '/#organization' } },
      { '@type': 'WebPage', '@id': canonical + '#webpage', url: canonical, name: title, description, inLanguage: 'es-AR', isPartOf: { '@id': SITE_URL + '/#website' } },
    ],
  };
  const metadata = `<meta name="robots" content="${isPublic ? 'index,follow,max-image-preview:large' : 'noindex,nofollow'}"><link rel="canonical" href="${escape(canonical)}"><meta property="og:type" content="website"><meta property="og:locale" content="es_AR"><meta property="og:site_name" content="Oriavision"><meta property="og:title" content="${escape(title)}"><meta property="og:description" content="${escape(description)}"><meta property="og:url" content="${escape(canonical)}"><meta property="og:image" content="${escape(image)}"><meta name="twitter:card" content="summary_large_image"><meta name="twitter:title" content="${escape(title)}"><meta name="twitter:description" content="${escape(description)}"><meta name="twitter:image" content="${escape(image)}"><script type="application/ld+json">${scriptJson(schema)}</script>`;
  html = html.replace('</head>', metadata + '</head>');
  if (isPublic) {
    // Preserve the production property's existing analytics integration.
    html = html.replace('</body>', '<script src="/site-analytics.js" defer></script></body>');
    publicPages.push(pathname);
  }
  await writeFile(destination, html);
}

const redirectLines = ['# Generated by scripts/build-reference-site.mjs. Cloudflare Pages permanent redirects.'];
for (const [from, to] of Object.entries(legacyRoutes)) {
  redirectLines.push(`${from.slice(0, -1)} ${to} 301`, `${from} ${to} 301`);
  const target = SITE_URL + to;
  const destination = join(output, from, 'index.html');
  await mkdir(resolve(destination, '..'), { recursive: true });
  await writeFile(destination, `<!doctype html><html lang="es-AR"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Página trasladada · Oriavision</title><meta name="robots" content="noindex,follow"><link rel="canonical" href="${escape(target)}"><meta http-equiv="refresh" content="0;url=${escape(to)}"></head><body><p>Esta página tiene una nueva dirección. <a href="${escape(to)}">Continuar en Oriavision</a>.</p><script>const target=new URL(${scriptJson(to)},location.origin);target.search=location.search;if(location.hash)target.hash=location.hash;location.replace(target.href);</script></body></html>`);
}
redirectLines.push('/web/* /servicios/diseno-web/ 301',
  '/demos/abogados-espresso-imagen /demos/abogados-espresso-editorial/ 301',
  '/demos/abogados-espresso-imagen/ /demos/abogados-espresso-editorial/ 301',
  '/demos/abogados-espresso-imagen/* /demos/abogados-espresso-editorial/:splat 301');
await writeFile(join(output, '_redirects'), redirectLines.join('\n') + '\n');

// Keep the old published resources in discovery, replace migrated canonicals,
// and add every public page from the reference (but never the motion test page).
const oldSitemap = load(await readFile(join(output, 'sitemap.xml'), 'utf8'), { xml: true });
const entries = new Map();
oldSitemap('url').each((_, element) => {
  const url = oldSitemap(element);
  const loc = url.find('loc').text();
  const pathname = new URL(loc).pathname;
  if (!legacyRoutes[pathname]) entries.set(pathname, oldSitemap.xml(element));
});
for (const pathname of publicPages) entries.set(pathname, `<url><loc>${escape(SITE_URL + pathname)}</loc><changefreq>${pathname === '/' ? 'weekly' : 'monthly'}</changefreq><priority>${pathname === '/' ? '1.0' : '0.8'}</priority></url>`);
await writeFile(join(output, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${[...entries.values()].join('\n')}\n</urlset>\n`);
await writeFile(join(output, 'robots.txt'), `User-agent: *\nAllow: /\nDisallow: /api/\nDisallow: /admin/\nDisallow: /pruebas/\n\nSitemap: ${SITE_URL}/sitemap.xml\n`);
await writeFile(join(output, 'site-analytics.js'), `window.dataLayer=window.dataLayer||[];function gtag(){dataLayer.push(arguments)}gtag('js',new Date());gtag('config','G-P7CCCZEQGN');const script=document.createElement('script');script.async=true;script.src='https://www.googletagmanager.com/gtag/js?id=G-P7CCCZEQGN';document.head.appendChild(script);\n`);

// A real 404 for unknown URLs, in the same visual language; valid routes are
// physical directories and never depend on a blanket home-page fallback.
const notFound = `<!doctype html><html lang="es-AR"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Página no encontrada · Oriavision</title><meta name="robots" content="noindex,follow"><link rel="stylesheet" href="/experience.css"><link rel="stylesheet" href="/buttons.css"></head><body>${referenceHome('header').prop('outerHTML').replaceAll(SITE_URL, '')}<main class="section wrap" id="contenido"><p>404</p><h1>Esta página no está disponible.</h1><p>Podés volver al inicio o explorar nuestros trabajos.</p><p><a class="button button-dark" href="/">Volver al inicio</a> <a class="underlined" href="/trabajos/">Ver trabajos</a></p></main>${referenceHome('footer').prop('outerHTML').replaceAll(SITE_URL, '')}<script src="/experience.js" defer></script></body></html>`;
await writeFile(join(output, '404.html'), notFound);
await mkdir(join(output, '404'), { recursive: true });
await writeFile(join(output, '404/index.html'), notFound);
console.log(`Reference v53: ${publicPages.length} public pages, ${Object.keys(legacyRoutes).length} legacy redirects, ${entries.size} sitemap URLs.`);
